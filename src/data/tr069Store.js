let _devices = [...INITIAL_DEVICES]
const _listeners = []
let _nextSeq = 16

function notify() { _listeners.forEach(fn => fn([..._devices])) }

export function getTr069Devices() { return [..._devices] }

export function getTr069DeviceByCustomerId(customerId) {
  return _devices.find(d => d.customerId === customerId) ?? null
}

export function getTr069DeviceBySerial(serial) {
  return _devices.find(d => d.serialNumber === serial) ?? null
}

export function addTr069Device(device) {
  const id = `TR-${String(_nextSeq++).padStart(3, '0')}`
  const record = { ...device, id }
  _devices = [record, ..._devices]
  notify()
  return record
}

export function updateTr069Device(id, fields) {
  _devices = _devices.map(d => d.id === id ? { ...d, ...fields } : d)
  notify()
}

export function deleteTr069Device(id) {
  _devices = _devices.filter(d => d.id !== id)
  notify()
}

export function subscribeTr069Devices(fn) {
  _listeners.push(fn)
  return () => { const i = _listeners.indexOf(fn); if (i >= 0) _listeners.splice(i, 1) }
}

export function getOnlineCount()     { return _devices.filter(d => d.status === 'Online').length }
export function getOfflineCount()    { return _devices.filter(d => d.status === 'Offline').length }
export function getAssignedCount()   { return _devices.filter(d => d.customerId !== '').length }
export function getUnassignedCount() { return _devices.filter(d => d.customerId === '').length }
